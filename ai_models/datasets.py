def build_weak_password_corpus():
    corpus = []
    for base in _BASE_WORDS:
        for pre in _PREFIXES:
            for suf in _SUFFIXES:
                corpus.append(f"{pre}{base}{suf}")
    corpus += _KEYBOARD_WALKS
    for w in _KEYBOARD_WALKS:
        for suf in ["", "123", "!", "2025"]:
            corpus.append(w + suf)
    # org/club-specific patterns
    for org in ["granit", "vpk", "гранит", "bronya", "granitvpk"]:
        for suf in _SUFFIXES:
            corpus.append(org + suf)
    return sorted(set(corpus))


