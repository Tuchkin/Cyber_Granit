def build_osint_dataset(per_class=45):
    data = []
    seen = set()
    for _ in range(per_class * 4):
        if len([x for x in data if x[1] == "leak_risk"]) >= per_class:
            break
        tpl = random.choice(_RISK_TEMPLATES)
        text = tpl.format(who=random.choice(_PEOPLE), detail=random.choice(_RISK_DETAILS))
        if text not in seen:
            seen.add(text)
            data.append((text, "leak_risk"))
    for _ in range(per_class * 4):
        if len([x for x in data if x[1] == "safe"]) >= per_class:
            break
        tpl = random.choice(_SAFE_TEMPLATES_OSINT)
        text = tpl.format(who=random.choice(_PEOPLE), detail=random.choice(_SAFE_DETAILS))
        if text not in seen:
            seen.add(text)
            data.append((text, "safe"))

    canonical = [
        ("Селфи в штабе, где на заднем плане видна доска с расписанием дежурств и картой района.", "leak_risk"),
        ("Фото в камуфляже на фоне городского памятника с геометкой центра города.", "safe"),
        ("Текстовый пост: устал после марш-броска, завтра снова на тренировку.", "safe"),
    ]
    data += canonical
    data += [(t, "leak_risk") for t in _HARD_OSINT_RISK]
    data += [(t, "safe") for t in _HARD_OSINT_SAFE]
    random.shuffle(data)
    return data


