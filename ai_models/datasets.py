def _fill(tpl, **overrides):
    vals = {
        "role": random.choice(_ROLES),
        "sender": random.choice(_SENDERS_FAKE),
        "link": random.choice(_LINKS),
        "attach": random.choice(_ATTACH),
        "year": random.choice(_YEARS),
        "amount": random.choice(_AMOUNTS),
        "obj": random.choice(_OBJECTS),
        "place": random.choice(_PLACES),
        "authority": random.choice(_AUTHORITIES_FAKE),
        "contact": random.choice(_CONTACTS),
        "rumor": random.choice(_RUMORS),
        "src": random.choice(_OFFICIAL_SRC),
        "d1": random.choice(_DATES),
        "d2": str(int(random.choice(_DATES)) + random.randint(1, 4)),
        "weekday": random.choice(_WEEKDAYS),
        "time": random.choice(_TIMES),
    }
    vals.update(overrides)
    return tpl.format(**vals)


def _generate(templates, label, count):
    out = []
    seen = set()
    attempts = 0
    while len(out) < count and attempts < count * 20:
        attempts += 1
        tpl = random.choice(templates)
        text = _fill(tpl)
        if text not in seen:
            seen.add(text)
            out.append((text, label))
    return out


